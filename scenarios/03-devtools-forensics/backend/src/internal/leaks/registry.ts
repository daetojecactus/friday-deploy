// --- сверка ответа ----------------------------------------------------------

export type MatchResult =
  | { kind: 'match'; leak: Leak }
  | { kind: 'too-broad' }
  | { kind: 'bare-host' }
  | { kind: 'miss' };

// Порядок проверок важен: сначала точное совпадение, потом «слишком общо», и
// только потом «это хост». Иначе адрес самого контура, названный вместо
// конкретной ручки, попал бы не в ту ветку разбора.
export function matchAnswer(raw: string): MatchResult {
  const value = normalize(raw);
  if (!value) return { kind: 'miss' };

  for (const leak of LEAKS) {
    const forms = [leak.marker, ...leak.aliases].map(normalize);
    if (forms.includes(value)) return { kind: 'match', leak };
  }

  // Назвали общий префикс («/report/», «/db/v1/») — направление верное, но это
  // ещё не адрес. Ведущему полезно сказать об этом вслух.
  if (LEAKS.some((leak) => normalize(leak.marker).startsWith(`${value}/`)))
    return { kind: 'too-broad' };

  if (looksLikeBareHost(value)) return { kind: 'bare-host' };

  return { kind: 'miss' };
}
