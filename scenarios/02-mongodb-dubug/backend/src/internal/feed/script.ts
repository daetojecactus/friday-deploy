// Тексты рабочего чата #incidents.
//
// Правило жанра: пишут коллеги, а не мониторинг. Никаких «TTL», «индекс»,
// «валидатор» — только симптом, его бизнес-цена и бытовые детали, которые сужают
// поиск («почта у всех разная», «объем данных тот же, что вчера»). Один раз на
// инцидент допускается назвать ожидаемое значение — как продакт, который помнит,
// как должно быть.
//
// Правило тона: это чат, а не служебная записка. Короткие фразы, живая речь,
// раздражение и усталость там, где они уместны. Не «Уважаемые коллеги, сообщаю о
// проблеме», а «Витрина пустая. Вообще». Благодарность — одна строка, без
// восторгов и канцелярита.

export type Line = { author: string; role: string; emoji: string; text: string };

export type IncidentScript = {
  complaint: Line[];
  escalation: Line;
  thanks: Line;
  regress: Line;
};

